def word_f1(answer, reference):
    def words(s): return collections.Counter(re.findall(r'\w+', s.lower()))
    a,b=words(answer),words(reference)
    common=sum((a&b).values())
    return 2*common/(sum(a.values())+sum(b.values())) if a and b else 0.0
