    with (model.disable_adapter() if disable_adapter else nullcontext()):
        for row in EVAL_ROWS:
            inputs=tokenizer.apply_chat_template(messages_for(row['prompt']),
                tokenize=True, add_generation_prompt=True, return_tensors='pt', return_dict=True).to('cuda')
